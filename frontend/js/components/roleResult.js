import { badges, html } from '../utils/dom.js';
import { clampPercent } from '../utils/formatters.js';

export function renderRoleResult(role) {
  const usesAiProfile = !role.roleProfileFound;

  return html`
    <section class="result-section role-card">
      <h4>Detected Role</h4>
      <p class="role-name">${role.detectedRole}</p>
      ${role.roleProfileFound && role.normalizedRole !== role.detectedRole
        ? html`<p class="muted">Scored against the "${role.normalizedRole}" profile.</p>`
        : ''}
      <p><strong>AI-estimated confidence:</strong> ${role.confidence}% (${role.confidenceLevel})</p>
      <div class="progress-container">
        <div class="progress-bar confidence-bar" style="width:${clampPercent(role.confidence)}%"></div>
      </div>
      <p class="muted">
        This is the AI's own estimate based on evidence in your resume, not a verified probability.
      </p>
      <p><strong>Why:</strong> ${role.reason}</p>
      ${role.alternativeRoles.length > 0
        ? html`<p><strong>Alternative roles:</strong></p>${badges(role.alternativeRoles, 'role-badge', '')}`
        : ''}
      ${usesAiProfile
        ? html`<p class="muted">
            No curated profile exists for this role yet, so the ATS keywords were generated by AI from your
            resume. Treat this score as indicative.
          </p>`
        : ''}
    </section>
  `;
}
