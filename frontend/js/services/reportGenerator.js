import { REPORT_FILENAME, SCORE_MAX } from '../utils/constants.js';
import { formatList } from '../utils/formatters.js';

const DOUBLE_LINE = '================================';
const SINGLE_LINE = '--------------------------------';

const formatLines = (items) => (items.length > 0 ? items.join('\n') : 'None identified');

const section = (title, body) => `${SINGLE_LINE}\n${title}\n${SINGLE_LINE}\n\n${body}\n`;

/** Builds the plain-text report from the analysis shown on screen. */
export function generateReportText({ file, role, ats, status, insights, aiFeedback }) {
  return [
    `${DOUBLE_LINE}\n      AI RESUME ANALYZER\n${DOUBLE_LINE}\n`,
    `File Name: ${file.name}\nFile Size: ${file.size} KB\nTotal Pages: ${file.totalPages}\n`,
    section(
      'DETECTED ROLE',
      [
        `Role: ${role.detectedRole}`,
        `AI-Estimated Confidence: ${role.confidence}% (${role.confidenceLevel})`,
        `Alternative Roles: ${formatList(role.alternativeRoles)}`,
        `Reason: ${role.reason}`,
        `Profile: ${role.roleProfileFound ? 'Curated' : 'AI-generated'} (${role.normalizedRole})`,
      ].join('\n'),
    ),
    section(
      'ATS SCORE',
      [
        `Score: ${ats.atsScore}/100`,
        `Status: ${status}`,
        '',
        'Breakdown:',
        `Skills: ${ats.skillScore}/${SCORE_MAX.skills}`,
        `Sections: ${ats.sectionScore}/${SCORE_MAX.sections}`,
        `Action Words: ${ats.actionScore}/${SCORE_MAX.actions}`,
      ].join('\n'),
    ),
    section('SKILLS FOUND', formatList(ats.foundSkills)),
    section('MISSING SKILLS', formatList(ats.missingSkills)),
    section(
      'RESUME SECTIONS',
      `Found Sections:\n${formatList(ats.foundSections)}\n\nMissing Sections:\n${formatList(ats.missingSections)}`,
    ),
    section(
      'ACTION WORDS',
      `Found:\n${formatList(ats.foundActionWords)}\n\nMissing:\n${formatList(ats.missingActionWords)}`,
    ),
    section('STRENGTHS', formatLines(insights.strengths)),
    section('WEAKNESSES', formatLines(insights.weaknesses)),
    section('SUGGESTIONS', formatLines(insights.suggestions)),
    section('AI FEEDBACK', aiFeedback),
    `${DOUBLE_LINE}\nGenerated By AI Resume Analyzer\n${DOUBLE_LINE}\n`,
  ].join('\n');
}

export function downloadReport(reportText) {
  const url = URL.createObjectURL(new Blob([reportText], { type: 'text/plain' }));
  const link = document.createElement('a');
  link.href = url;
  link.download = REPORT_FILENAME;
  link.click();
  setTimeout(() => URL.revokeObjectURL(url), 0);
}
